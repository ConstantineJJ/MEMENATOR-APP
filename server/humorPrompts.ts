export function getHumorProfile(styleId: string): HumorStyleProfile {
  return PROFILES[styleId] || PROFILES.trending;
}

function formatRecentIdeas(recentCaptions: RecentCaptionIdea[] = []): string {
  const ideas = recentCaptions
    .slice(0, 9)
    .map((caption) => [caption.headline, caption.topText, caption.bottomText].filter(Boolean).join(' / '))
    .filter(Boolean);

  if (ideas.length === 0) {
    return 'Недавних идей нет. Все равно избегай самых очевидных мемных автопилотов.';
  }

  return `Недавно пользователь уже видел такие идеи. НЕ повторяй их сюжет, ключевой объект или панчлайн:\n${ideas
    .map((idea, index) => `${index + 1}. ${idea}`)
    .join('\n')}`;
}

function formatComposition(context?: CompositionPromptContext): string {
  if (!context) return 'Дополнительного анализа композиции нет — опирайся на само изображение.';

  const subjects = (context.focalSubjects || [])
    .slice(0, 5)
    .map((subject) =>
      `- ${subject.name || 'Субъект'} (${subject.role || 'фокус'}), взгляд: ${subject.gazeDirection || 'не указан'}; ${subject.description || ''}`
    )
    .join('\n');

  return [
    `Стиль композиции: ${context.detectedStyle || 'не указан'}`,
    `Баланс: ${context.balanceAssessment || 'не указан'}`,
    subjects ? `Ключевые субъекты:\n${subjects}` : '',
  ].filter(Boolean).join('\n');
}

export function buildMagicCaptionPrompt({
  styleId,
  customContext = '',
  compositionContext,
  recentCaptions = [],
}: MagicCaptionPromptInput): string {
  const profile = getHumorProfile(styleId);
  const topicLine = customContext.trim()
    ? `Пользовательская тема: «${customContext.trim()}». Используй ее только если она естественно пересекается с тем, что реально видно.`
    : 'Пользовательская тема не задана.';

  return `Ты — сильный комедийный редактор и мем-сценарист. Твоя задача — вернуть РОВНО 3 готовых варианта мема на русском языке.

ВАЖНО: перед финальным ответом МОЛЧА придумай минимум 9 разных углов шутки, оцени их по визуальной точности, свежести, силе панчлайна и непохожести друг на друга, отбрось слабые и выдай только лучшие 3. Черновики не показывай.

ВЫБРАННЫЙ СТИЛЬ: ${profile.nameRu}
ЗАДАЧА СТИЛЯ: ${profile.mission}
${topicLine}

АНАЛИЗ КАДРА:
Сначала реально посмотри на изображение и зафиксируй для себя: кто/что в кадре, мимику, взгляд, позу, действие, одежду, предметы, окружение и главное визуальное противоречие. Не подменяй увиденное знакомым мемным шаблоном.

ДАННЫЕ КОМПОЗИЦИИ:
${formatComposition(compositionContext)}

РАЗНООБРАЗИЕ СТИЛЯ — ВЫБИРАЙ ИЗ ЭТИХ ОБЛАСТЕЙ, НО НЕ КОПИРУЙ ИХ КАК ГОТОВЫЕ ШУТКИ:
${profile.domains.map((domain) => `- ${domain}`).join('\n')}

АНТИ-КЛИШЕ ДЛЯ ЭТОГО СТИЛЯ:
${profile.avoid.map((item) => `- Не скатывайся автоматически в: ${item}.`).join('\n')}

НЕДАВНИЕ ИДЕИ:
${formatRecentIdeas(recentCaptions)}

ОБЩИЕ ПРАВИЛА КАЧЕСТВА:
${profile.qualityRules.map((rule, index) => `${index + 1}. ${rule}`).join('\n')}

МЕХАНИКИ ЮМОРА:
${HUMOR_MECHANICS.map((mechanic, index) => `${index + 1}. ${mechanic}`).join('\n')}

ТРЕБОВАНИЯ К ТРЕМ ФИНАЛИСТАМ:
1. Ровно 3 варианта.
2. У всех трех разные humorMechanic.
3. У всех трех разные смысловые сюжеты; нельзя выдавать три перефразировки одной мысли.
4. По возможности используй разные детали изображения и разные домены выбранного стиля.
5. Сетап и панчлайн должны быть короткими и пригодными для текста непосредственно на мем-картинке.
6. Каждый вариант должен пройти внутреннюю проверку: «без этой конкретной картинки шутка заметно теряет смысл?» Если нет — перепиши.
7. Не поясняй правила и не показывай внутренний отбор.

ФОРМАТ КАЖДОГО ОБЪЕКТА:
- headline: короткое название 2–4 слова
- topText: верхняя строка / сетап
- bottomText: нижняя строка / панчлайн
- style: «${profile.nameRu}»
- humorMechanic: одна механика из списка выше
- imageConnection: одно конкретное предложение, доказывающее связь с видимой деталью кадра
- explanation: одно короткое предложение, почему работает шутка
- visualContradiction: главное визуальное противоречие
- spottedDetail: конкретная микро-деталь кадра, на которой держится идея
- detectedMood: настроение персонажа или сцены

Верни только JSON-массив из ровно трех объектов.`;
}
